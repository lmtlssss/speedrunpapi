# Exhaustive check of ac_math::ac_div and ac_math::ac_sqrt on small ac_fixed and ac_int types.
#
# usage: python3 acm.py gen OUT_DIR [PARTS]    writes t_0.cpp .. t_{PARTS-1}.cpp and configs.json into OUT_DIR
#        python3 acm.py check OUT_DIR RESULTS.txt [examples]
#
# Each configuration is one instantiation of the library function with fixed widths, quantization mode and
# overflow mode. The C++ runs every operand value of the configuration and prints one line per call:
#   id  operand raw bits (hex) ...  result raw bits (hex)  returned flag
# The reference does the operation on fractions of integers and quantizes once, by the definitions of the
# Algorithmic C quantization modes:
#   AC_TRN toward minus infinity, AC_TRN_ZERO toward zero, AC_RND nearest with ties toward plus infinity,
#   AC_RND_ZERO ties toward zero, AC_RND_INF ties away from zero, AC_RND_MIN_INF ties toward minus infinity,
#   AC_RND_CONV ties to even, AC_RND_CONV_ODD ties to odd;
# and the overflow modes AC_WRAP (keep the low bits) and AC_SAT (clamp to the range).
import json
import os
import sys
from fractions import Fraction
from math import isqrt

QMODES = ["AC_TRN", "AC_TRN_ZERO", "AC_RND", "AC_RND_ZERO", "AC_RND_INF", "AC_RND_MIN_INF", "AC_RND_CONV", "AC_RND_CONV_ODD"]
OMODES = ["AC_WRAP", "AC_SAT"]

DIV_N = [(4, 2), (4, 4), (3, 0), (4, 5), (3, -1)]
DIV_D = [(4, 2), (3, 3), (4, 0), (3, 4)]
DIV_Q = [(5, 3), (6, 2), (4, 4), (4, 0), (5, 6), (3, -1), (8, 4)]
SQRT_X = [(4, 2), (4, 4), (5, 0), (4, 6), (3, -1), (6, 3), (5, 1), (7, 4), (6, 6)]
SQRT_O = [(5, 3), (6, 2), (4, 4), (4, 0), (3, -1), (8, 4), (4, 1), (3, 3), (6, 1)]
IDIV = [(4, 4, 4, 4), (5, 3, 5, 3), (4, 4, 3, 2), (3, 5, 6, 6), (6, 2, 4, 3)]      # NW, DW, QW, RW
ISQRT = [(4, 2), (5, 3), (6, 3), (7, 4), (8, 4), (8, 2), (5, 6), (9, 5)]              # XW, OW


def configs():
    out = []
    for s in (0, 1):
        for n in DIV_N:
            for d in DIV_D:
                for q in DIV_Q:
                    for qq in QMODES:
                        for qo in OMODES:
                            out.append({"op": "fdiv", "s": s, "n": n, "d": d, "q": q, "qq": qq, "qo": qo})
    for x in SQRT_X:
        for o in SQRT_O:
            for qq in QMODES:
                for qo in OMODES:
                    out.append({"op": "fsqrt", "x": x, "o": o, "qq": qq, "qo": qo})
    for s in (0, 1):
        for c in IDIV:
            out.append({"op": "idiv", "s": s, "c": c})
    for c in ISQRT:
        for os_ in (0, 1):
            out.append({"op": "isqrt", "c": c, "os": os_})
    for i, c in enumerate(out):
        c["id"] = i
    return out


HEAD = r'''// generated by acm.py; every operand of each small configuration through ac_math::ac_div and ac_math::ac_sqrt
// The library's assertions go through its own hook and are thrown, so that a call that trips one is reported
// on its line ("A" and the header line of the assertion) and the run goes on.
struct ac_fail { const char *file; int line; const char *msg; };
#define AC_USER_DEFINED_ASSERT(cond, file, line, msg) do { if (!(cond)) throw ac_fail{file, line, msg}; } while (0)
#include <iostream>   // ac_fixed.h uses std::cerr and includes this header itself only without the hook
#include <ac_int.h>
#include <ac_fixed.h>
#include <ac_math/ac_div.h>
#include <ac_math/ac_sqrt.h>
#include <cstdio>
#include <cstdlib>

// Every output variable is filled with this before the call (first argument of the program, hex). A result that
// changes with it was not written by the function, or was built from a variable that was never set.
static unsigned SENT = 0;

template<int W, int I, bool S> static ac_fixed<W, I, S> raw(unsigned v) {
  ac_fixed<W, I, S> x;
  x.set_slc(0, ac_int<W, false>(v));
  return x;
}
template<int W, int I, bool S, ac_q_mode Q, ac_o_mode O> static unsigned long long bits(const ac_fixed<W, I, S, Q, O> &x) {
  return (unsigned long long) x.template slc<W>(0).to_uint64() & ((1ULL << W) - 1);
}
template<int W, bool S> static unsigned long long ibits(const ac_int<W, S> &x) {
  return (unsigned long long) x.to_uint64() & ((1ULL << W) - 1);
}

template<int NW, int NI, int DW, int DI, int QW, int QI, ac_q_mode QQ, ac_o_mode QO, bool S>
static void fdiv(int id) {
  for (unsigned n = 0; n < (1u << NW); n++)
    for (unsigned d = 1; d < (1u << DW); d++) {
      try {
        ac_fixed<QW, QI, S, QQ, QO> q;
        q.set_slc(0, ac_int<QW, false>(SENT));           // what the variable held before the call
        bool rem = ac_math::ac_div(raw<NW, NI, S>(n), raw<DW, DI, S>(d), q);
        printf("%d %x %x %llx %d\n", id, n, d, bits(q), (int) rem);
      } catch (const ac_fail &f) { printf("%d %x %x A %d\n", id, n, d, f.line); }
    }
}
template<int XW, int XI, int OW, int OI, ac_q_mode OQ, ac_o_mode OO>
static void fsqrt(int id) {
  for (unsigned x = 0; x < (1u << XW); x++) {
    try {
      ac_fixed<OW, OI, false, OQ, OO> r;
      r.set_slc(0, ac_int<OW, false>(SENT));
      ac_math::ac_sqrt(raw<XW, XI, false>(x), r);
      printf("%d %x %llx\n", id, x, bits(r));
    } catch (const ac_fail &f) { printf("%d %x A %d\n", id, x, f.line); }
  }
}
template<int NW, int DW, int QW, int RW, bool S>
static void idiv(int id) {
  for (unsigned n = 0; n < (1u << NW); n++)
    for (unsigned d = 1; d < (1u << DW); d++) {
      ac_int<NW, S> N;
      ac_int<DW, S> D;
      N.set_slc(0, ac_int<NW, false>(n));
      D.set_slc(0, ac_int<DW, false>(d));
      try {
        ac_int<QW, S> q;
        ac_int<RW, S> r;
        q.set_slc(0, ac_int<QW, false>(SENT));
        r.set_slc(0, ac_int<RW, false>(SENT));
        bool rem = ac_math::ac_div(N, D, q, r);
        printf("%d %x %x %llx %llx %d\n", id, n, d, ibits(q), ibits(r), (int) rem);
      } catch (const ac_fail &f) { printf("%d %x %x A %d\n", id, n, d, f.line); }
    }
}
template<int XW, int OW, bool OS>
static void isqrt_(int id) {
  for (unsigned x = 0; x < (1u << XW); x++) {
    try {
      ac_int<OW, OS> r;
      r.set_slc(0, ac_int<OW, false>(SENT));
      ac_math::ac_sqrt(ac_int<XW, false>(x), r);
      printf("%d %x %llx\n", id, x, ibits(r));
    } catch (const ac_fail &f) { printf("%d %x A %d\n", id, x, f.line); }
  }
}

int main(int argc, char **argv) {
  SENT = argc > 1 ? (unsigned) strtoul(argv[1], 0, 16) : 0;
'''


def call(c):
    b = lambda v: "true" if v else "false"
    if c["op"] == "fdiv":
        return "  fdiv<%d, %d, %d, %d, %d, %d, %s, %s, %s>(%d);\n" % (*c["n"], *c["d"], *c["q"], c["qq"], c["qo"], b(c["s"]), c["id"])
    if c["op"] == "fsqrt":
        return "  fsqrt<%d, %d, %d, %d, %s, %s>(%d);\n" % (*c["x"], *c["o"], c["qq"], c["qo"], c["id"])
    if c["op"] == "idiv":
        return "  idiv<%d, %d, %d, %d, %s>(%d);\n" % (*c["c"], b(c["s"]), c["id"])
    return "  isqrt_<%d, %d, %s>(%d);\n" % (*c["c"], b(c["os"]), c["id"])


def gen(out_dir, parts):
    cs = configs()
    os.makedirs(out_dir, exist_ok=True)
    json.dump(cs, open(os.path.join(out_dir, "configs.json"), "w"))
    skip_path = os.path.join(out_dir, "nocompile.json")
    skip = set(json.load(open(skip_path))) if os.path.exists(skip_path) else set()
    use = [c for c in cs if c["id"] not in skip]
    for p in range(parts):
        with open(os.path.join(out_dir, "t_%d.cpp" % p), "w") as f:
            f.write(HEAD)
            for c in use[p::parts]:
                f.write(call(c))
            f.write("  return 0;\n}\n")
    print(len(use), "configurations in", parts, "files;", len(skip), "left out because the library does not compile for them")


# ---- the reference --------------------------------------------------------------------------------
def signed(v, w):
    return v - (1 << w) if v >> (w - 1) else v


def value(rawbits, w, i, s):
    return Fraction(signed(rawbits, w) if s else rawbits, 1) * Fraction(2) ** (i - w)


def quantize(r, mode):
    """the integer nearest the fraction r in the given mode"""
    fl = r.numerator // r.denominator
    frac = r - fl
    if frac == 0:
        return fl
    if mode == "AC_TRN":
        return fl
    if mode == "AC_TRN_ZERO":
        return fl if r > 0 else fl + 1
    half = Fraction(1, 2)
    if frac != half:
        return fl + (1 if frac > half else 0)
    up = {"AC_RND": True, "AC_RND_ZERO": r < 0, "AC_RND_INF": r > 0, "AC_RND_MIN_INF": False,
          "AC_RND_CONV": fl % 2 == 1, "AC_RND_CONV_ODD": fl % 2 == 0}[mode]
    return fl + (1 if up else 0)


def overflow(k, w, s, mode):
    lo, hi = (-(1 << (w - 1)), (1 << (w - 1)) - 1) if s else (0, (1 << w) - 1)
    if mode == "AC_SAT":
        k = min(max(k, lo), hi)
    return k & ((1 << w) - 1)


def sqrt_quantize(t, mode):
    """the integer nearest sqrt(t) in the given mode, t a non-negative fraction"""
    k = isqrt(t.numerator // t.denominator)
    if t == k * k:
        return k
    if mode in ("AC_TRN", "AC_TRN_ZERO"):
        return k
    four_t, mid = 4 * t, (2 * k + 1) ** 2
    if four_t != mid:
        return k + (1 if four_t > mid else 0)
    up = {"AC_RND": True, "AC_RND_ZERO": False, "AC_RND_INF": True, "AC_RND_MIN_INF": False,
          "AC_RND_CONV": k % 2 == 1, "AC_RND_CONV_ODD": k % 2 == 0}[mode]
    return k + (1 if up else 0)


def expected(c, f):
    op = c["op"]
    if op == "fdiv":
        s = c["s"]
        n = value(int(f[1], 16), *c["n"], s)
        d = value(int(f[2], 16), *c["d"], s)
        qw, qi = c["q"]
        r = n / d * Fraction(2) ** (qw - qi)
        want = overflow(quantize(r, c["qq"]), qw, s, c["qo"])
        return want, int(f[3], 16), (int(r.denominator != 1), int(f[4]))
    if op == "fsqrt":
        x = value(int(f[1], 16), *c["x"], 0)
        ow, oi = c["o"]
        t = x * Fraction(4) ** (ow - oi)
        return overflow(sqrt_quantize(t, c["qq"]), ow, 0, c["qo"]), int(f[2], 16), None
    if op == "idiv":
        nw, dw, qw, rw = c["c"]
        s = c["s"]
        n = signed(int(f[1], 16), nw) if s else int(f[1], 16)
        d = signed(int(f[2], 16), dw) if s else int(f[2], 16)
        q = abs(n) // abs(d) * (1 if (n < 0) == (d < 0) else -1)       # toward zero, as C divides
        r = n - q * d
        want = (q & ((1 << qw) - 1)) | ((r & ((1 << rw) - 1)) << 32)
        got = int(f[3], 16) | (int(f[4], 16) << 32)
        return want, got, (int(r != 0), int(f[5]))
    xw, ow = c["c"]
    return isqrt(int(f[1], 16)) & ((1 << ow) - 1), int(f[2], 16), None


def operands_of(c):
    """how many fields of a result line are operands"""
    return 2 if c["op"] in ("fdiv", "idiv", "shift") else 1


def describe(c):
    if c["op"] == "fdiv":
        return "ac_div %s ac_fixed<%d,%d> / <%d,%d> -> <%d,%d,%s,%s>" % ("signed" if c["s"] else "unsigned", *c["n"], *c["d"], *c["q"], c["qq"], c["qo"])
    if c["op"] == "fsqrt":
        return "ac_sqrt ac_fixed<%d,%d> -> <%d,%d,%s,%s>" % (*c["x"], *c["o"], c["qq"], c["qo"])
    if c["op"] == "idiv":
        return "ac_div %s ac_int<%d> / <%d> -> q<%d> r<%d>" % ("signed" if c["s"] else "unsigned", *c["c"])
    return "ac_sqrt ac_int<%d> -> ac_int<%d,%s>" % (*c["c"], "true" if c["os"] else "false")


def check(out_dir, results, examples):
    cs = json.load(open(os.path.join(out_dir, "configs.json")))
    total = {}
    wrong = {}
    flagwrong = {}
    bad_cfg = {}
    shown = {}
    asserts = {}
    assert_cfg = {}
    for line in open(results):
        f = line.split()
        c = cs[int(f[0])]
        key = c["op"] + (" signed" if c.get("s") else "") + ((" " + c["qq"]) if "qq" in c else "")
        total[key] = total.get(key, 0) + 1
        if "A" in f:
            asserts[key] = asserts.get(key, 0) + 1
            if c["id"] not in assert_cfg:
                assert_cfg[c["id"]] = [0, f[-1], " ".join(f[1:f.index("A")])]
                if len(assert_cfg) <= 6:
                    print("  assertion at line %s of ac_fixed.h or ac_int.h: %s, operands %s" % (f[-1], describe(c), " ".join(f[1:f.index("A")])))
            assert_cfg[c["id"]][0] += 1
            continue
        want, got, flag = expected(c, f)
        if flag is not None and flag[0] != flag[1]:
            flagwrong[key] = flagwrong.get(key, 0) + 1
        if want != got:
            wrong[key] = wrong.get(key, 0) + 1
            bad_cfg[c["id"]] = bad_cfg.get(c["id"], 0) + 1
            if shown.get(key, 0) < examples:
                shown[key] = shown.get(key, 0) + 1
                print("  %s: operands %s -> %x, exact %x" % (describe(c), " ".join(f[1:1 + operands_of(c)]), got, want))
    print("%-34s %10s %9s %9s %9s" % ("operation and mode", "calls", "wrong", "flag", "asserts"))
    for key in sorted(total):
        print("%-34s %10d %9d %9d %9d" % (key, total[key], wrong.get(key, 0), flagwrong.get(key, 0), asserts.get(key, 0)))
    print("total %d calls, %d wrong values in %d configurations, %d calls stopped by an assertion in %d configurations, of %d configurations" % (
        sum(total.values()), sum(wrong.values()), len(bad_cfg), sum(asserts.values()), len(assert_cfg), len(cs)))
    json.dump(bad_cfg, open(os.path.join(out_dir, "bad_configs.json"), "w"))
    json.dump(assert_cfg, open(os.path.join(out_dir, "assert_configs.json"), "w"))


def depends(out_dir, path_a, path_b, examples):
    """Calls whose result changes with what the output variable held before the call."""
    cs = json.load(open(os.path.join(out_dir, "configs.json")))
    per, cfg, shown = {}, {}, 0
    with open(path_a) as a, open(path_b) as b:
        for la, lb in zip(a, b):
            if la == lb:
                continue
            fa, fb = la.split(), lb.split()
            c = cs[int(fa[0])]
            key = c["op"] + (" signed" if c.get("s") else "") + ((" " + c["qq"]) if "qq" in c else "")
            per[key] = per.get(key, 0) + 1
            cfg[c["id"]] = cfg.get(c["id"], 0) + 1
            if shown < examples and cfg[c["id"]] == 1:
                shown += 1
                print("  %s: operands %s -> %s with one earlier content, %s with another" % (
                    describe(c), " ".join(fa[1:1 + operands_of(c)]), " ".join(fa[1 + operands_of(c):]),
                    " ".join(fb[1 + operands_of(c):])))
    for key in sorted(per):
        print("%-34s %9d calls depend on the earlier content" % (key, per[key]))
    print("total %d calls in %d configurations give a result that depends on what the output variable held" % (sum(per.values()), len(cfg)))
    json.dump(cfg, open(os.path.join(out_dir, "depends_configs.json"), "w"))


if __name__ == "__main__":
    if sys.argv[1] == "gen":
        gen(sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 8)
    elif sys.argv[1] == "depends":
        depends(sys.argv[2], sys.argv[3], sys.argv[4], int(sys.argv[5]) if len(sys.argv) > 5 else 6)
    else:
        check(sys.argv[2], sys.argv[3], int(sys.argv[4]) if len(sys.argv) > 4 else 2)
