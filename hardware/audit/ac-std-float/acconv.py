# Exhaustive check of the conversions of ac_std_float<W,E>: to another float format, to ac_fixed, and from ac_fixed.
#
# usage: python3 acconv.py gen OUT_DIR [PARTS]       writes t_0.cpp .. and configs.json
#        python3 acconv.py check OUT_DIR RESULTS.txt [examples]
#
# Kinds of configuration, each one instantiation of a library template, run on every value of its source type:
#   f2f   ac_std_float<W,E>::convert<WR,ER,QR>()              float to float, four rounding modes
#   f2s   ac_std_float<W,E>::convert<WR,QR>()                 the same with the exponent width kept
#   f2x   ac_std_float<W,E>::convert_to_ac_fixed<WFX,IFX,SFX,QFX,OFX>()   finite floats only
#   x2f   ac_std_float<W,E>::assign_from<Q>(ac_fixed<WFX,IFX,SFX>)        what the constructors from fixed and int use
# The reference takes the exact value of the source as a fraction and rounds it once into the target: acref.py
# for a float target (overflow to infinity, or to the largest finite number under truncation; the sign of a zero
# kept; any NaN for a NaN), and the eight ac_fixed quantization modes with AC_WRAP and AC_SAT for a fixed target.
import json
import os
import sys
from fractions import Fraction

import acref

FLOAT_MODES = {"AC_RND_CONV": "conv", "AC_TRN_ZERO": "zero", "AC_RND_INF": "inf", "AC_RND_CONV_ODD": "odd"}
QMODES = ["AC_TRN", "AC_TRN_ZERO", "AC_RND", "AC_RND_ZERO", "AC_RND_INF", "AC_RND_MIN_INF", "AC_RND_CONV", "AC_RND_CONV_ODD"]
OMODES = ["AC_WRAP", "AC_SAT"]

SRC = [(8, 3), (8, 4), (9, 4), (10, 4), (10, 3)]
DST = [(6, 3), (7, 3), (8, 3), (9, 3), (10, 3), (6, 2), (7, 2), (8, 4), (9, 4), (10, 4), (9, 5), (11, 5), (12, 4)]
FIX = [(4, 4), (4, 2), (5, 0), (4, 6), (3, -1), (6, 3), (8, 4), (5, 5)]          # W, I
FLT = [(8, 3), (8, 4), (10, 4), (7, 3), (9, 5)]


def configs():
    out = []
    for s in SRC:
        for d in DST:
            if d == s:
                continue
            for q in FLOAT_MODES:
                out.append({"op": "f2f", "s": s, "d": d, "q": q})
                if d[1] == s[1]:
                    out.append({"op": "f2s", "s": s, "d": d, "q": q})
    for s in [(8, 3), (8, 4), (10, 4)]:
        for x in FIX:
            for sg in (0, 1):
                for q in QMODES:
                    for o in OMODES:
                        out.append({"op": "f2x", "s": s, "x": x, "sg": sg, "q": q, "o": o})
    for d in FLT:
        for x in FIX:
            for sg in (0, 1):
                for q in FLOAT_MODES:
                    out.append({"op": "x2f", "d": d, "x": x, "sg": sg, "q": q})
    for i, c in enumerate(out):
        c["id"] = i
    return out


HEAD = r'''// generated by acconv.py: every value of each source type through one conversion of ac_std_float
struct ac_fail { const char *file; int line; const char *msg; };
#define AC_USER_DEFINED_ASSERT(cond, file, line, msg) do { if (!(cond)) throw ac_fail{file, line, msg}; } while (0)
#include <iostream>
#include <ac_std_float.h>
#include <cstdio>

template<int W, int E, int WR, int ER, ac_q_mode QR> static void f2f(int id) {
  for (unsigned a = 0; a < (1u << W); a++) {
    try {
      ac_std_float<W, E> x;
      x.d = a;
      ac_std_float<WR, ER> r = x.template convert<WR, ER, QR>();
      printf("%d %x %llx\n", id, a, (unsigned long long) r.d.to_uint64() & ((1ULL << WR) - 1));
    } catch (const ac_fail &f) { printf("%d %x A %d\n", id, a, f.line); }
  }
}
template<int W, int E, int WR, ac_q_mode QR> static void f2s(int id) {
  for (unsigned a = 0; a < (1u << W); a++) {
    try {
      ac_std_float<W, E> x;
      x.d = a;
      ac_std_float<WR, E> r = x.template convert<WR, QR>();
      printf("%d %x %llx\n", id, a, (unsigned long long) r.d.to_uint64() & ((1ULL << WR) - 1));
    } catch (const ac_fail &f) { printf("%d %x A %d\n", id, a, f.line); }
  }
}
template<int W, int E, int WFX, int IFX, bool SFX, ac_q_mode QFX, ac_o_mode OFX> static void f2x(int id) {
  const unsigned emask = (1u << E) - 1;
  for (unsigned a = 0; a < (1u << W); a++) {
    if (((a >> (W - E - 1)) & emask) == emask) continue;          // infinities and NaNs are asserted against
    try {
      ac_std_float<W, E> x;
      x.d = a;
      ac_fixed<WFX, IFX, SFX, QFX, OFX> r = x.template convert_to_ac_fixed<WFX, IFX, SFX, QFX, OFX>();
      printf("%d %x %llx\n", id, a, (unsigned long long) r.template slc<WFX>(0).to_uint64() & ((1ULL << WFX) - 1));
    } catch (const ac_fail &f) { printf("%d %x A %d\n", id, a, f.line); }
  }
}
template<int W, int E, int WFX, int IFX, bool SFX, ac_q_mode Q> static void x2f(int id) {
  for (unsigned v = 0; v < (1u << WFX); v++) {
    try {
      ac_fixed<WFX, IFX, SFX> fx;
      fx.set_slc(0, ac_int<WFX, false>(v));
      ac_std_float<W, E> r;
      r.d = 0;
      r.template assign_from<Q>(fx);
      printf("%d %x %llx\n", id, v, (unsigned long long) r.d.to_uint64() & ((1ULL << W) - 1));
    } catch (const ac_fail &f) { printf("%d %x A %d\n", id, v, f.line); }
  }
}

int main() {
'''


def call(c):
    b = lambda v: "true" if v else "false"
    if c["op"] == "f2f":
        return "  f2f<%d, %d, %d, %d, %s>(%d);\n" % (*c["s"], *c["d"], c["q"], c["id"])
    if c["op"] == "f2s":
        return "  f2s<%d, %d, %d, %s>(%d);\n" % (*c["s"], c["d"][0], c["q"], c["id"])
    if c["op"] == "f2x":
        return "  f2x<%d, %d, %d, %d, %s, %s, %s>(%d);\n" % (*c["s"], *c["x"], b(c["sg"]), c["q"], c["o"], c["id"])
    return "  x2f<%d, %d, %d, %d, %s, %s>(%d);\n" % (*c["d"], *c["x"], b(c["sg"]), c["q"], c["id"])


def gen(out_dir, parts):
    cs = configs()
    os.makedirs(out_dir, exist_ok=True)
    json.dump(cs, open(os.path.join(out_dir, "configs.json"), "w"))
    skip_path = os.path.join(out_dir, "nocompile.json")
    skip = set(json.load(open(skip_path))) if os.path.exists(skip_path) else set()
    use = [c for c in cs if c["id"] not in skip]
    for p in range(parts):
        with open(os.path.join(out_dir, "t_%d.cpp" % p), "w") as f:
            f.write(HEAD)
            for c in use[p::parts]:
                f.write(call(c))
            f.write("  return 0;\n}\n")
    print(len(use), "configurations in", parts, "files;", len(skip), "left out because the library does not compile for them")


# ---- the reference --------------------------------------------------------------------------------
def signed(v, w):
    return v - (1 << w) if v >> (w - 1) else v


def quantize(r, mode):
    fl = r.numerator // r.denominator
    frac = r - fl
    if frac == 0:
        return fl
    if mode == "AC_TRN":
        return fl
    if mode == "AC_TRN_ZERO":
        return fl if r > 0 else fl + 1
    half = Fraction(1, 2)
    if frac != half:
        return fl + (1 if frac > half else 0)
    up = {"AC_RND": True, "AC_RND_ZERO": r < 0, "AC_RND_INF": r > 0, "AC_RND_MIN_INF": False,
          "AC_RND_CONV": fl % 2 == 1, "AC_RND_CONV_ODD": fl % 2 == 0}[mode]
    return fl + (1 if up else 0)


def overflow(k, w, s, mode):
    lo, hi = (-(1 << (w - 1)), (1 << (w - 1)) - 1) if s else (0, (1 << w) - 1)
    if mode == "AC_SAT":
        k = min(max(k, lo), hi)
    return k & ((1 << w) - 1)


def expected(c, f):
    """-> (want, got); want is acref.NAN when any NaN is right"""
    a = int(f[1], 16)
    got = int(f[2], 16)
    if c["op"] in ("f2f", "f2s"):
        src, dst = acref.Fmt(*c["s"]), acref.Fmt(*c["d"])
        kind, sign, mag = src.unpack(a)
        if kind == "nan":
            return acref.NAN, got
        if kind == "inf":
            return dst.inf(sign), got
        if kind == "zero":
            return dst.zero(sign), got
        return dst.round(sign, mag, FLOAT_MODES[c["q"]]), got
    if c["op"] == "f2x":
        src = acref.Fmt(*c["s"])
        kind, sign, mag = src.unpack(a)
        v = Fraction(0) if kind == "zero" else (-mag if sign else mag)
        w, i = c["x"]
        return overflow(quantize(v * Fraction(2) ** (w - i), c["q"]), w, c["sg"], c["o"]), got
    dst = acref.Fmt(*c["d"])
    w, i = c["x"]
    v = Fraction(signed(a, w) if c["sg"] else a) * Fraction(2) ** (i - w)
    if v == 0:
        return dst.zero(0), got
    return dst.round(int(v < 0), abs(v), FLOAT_MODES[c["q"]]), got


def describe(c):
    if c["op"] == "f2f":
        return "ac_std_float<%d,%d>::convert<%d,%d,%s>" % (*c["s"], *c["d"], c["q"])
    if c["op"] == "f2s":
        return "ac_std_float<%d,%d>::convert<%d,%s>" % (*c["s"], c["d"][0], c["q"])
    if c["op"] == "f2x":
        return "ac_std_float<%d,%d>::convert_to_ac_fixed<%d,%d,%s,%s,%s>" % (*c["s"], *c["x"], "true" if c["sg"] else "false", c["q"], c["o"])
    return "ac_std_float<%d,%d>::assign_from<%s>(ac_fixed<%d,%d,%s>)" % (*c["d"], c["q"], *c["x"], "true" if c["sg"] else "false")


def show(c, v):
    """a value of the target, readable"""
    if c["op"] == "f2x":
        w, i = c["x"]
        return str(Fraction(signed(v, w) if c["sg"] else v) * Fraction(2) ** (i - w))
    return acref.describe(acref.Fmt(*c["d"]), v)


def source(c, a):
    if c["op"] == "x2f":
        w, i = c["x"]
        return str(Fraction(signed(a, w) if c["sg"] else a) * Fraction(2) ** (i - w))
    return acref.describe(acref.Fmt(*c["s"]), a)


def check(out_dir, results, examples):
    cs = json.load(open(os.path.join(out_dir, "configs.json")))
    total, wrong, asserts, bad_cfg, assert_cfg, shown = {}, {}, {}, {}, {}, {}
    for line in open(results):
        f = line.split()
        c = cs[int(f[0])]
        key = c["op"] + " " + c["q"]
        total[key] = total.get(key, 0) + 1
        if "A" in f:
            asserts[key] = asserts.get(key, 0) + 1
            if c["id"] not in assert_cfg and len(assert_cfg) < 6:
                print("  assertion at header line %s: %s on %s (%s)" % (f[-1], describe(c), f[1], source(c, int(f[1], 16))))
            assert_cfg[c["id"]] = assert_cfg.get(c["id"], 0) + 1
            continue
        want, got = expected(c, f)
        if want == acref.NAN:
            ok = acref.Fmt(*c["d"]).is_nan(got)
        else:
            ok = want == got
        if not ok:
            wrong[key] = wrong.get(key, 0) + 1
            bad_cfg[c["id"]] = bad_cfg.get(c["id"], 0) + 1
            if shown.get(key, 0) < examples:
                shown[key] = shown.get(key, 0) + 1
                print("  %s on %s (%s) -> %x (%s), exact %s" % (
                    describe(c), f[1], source(c, int(f[1], 16)), got, show(c, got),
                    "nan" if want == acref.NAN else "%x (%s)" % (want, show(c, want))))
    print("%-24s %9s %8s %8s" % ("conversion and mode", "calls", "wrong", "asserts"))
    for key in sorted(total):
        print("%-24s %9d %8d %8d" % (key, total[key], wrong.get(key, 0), asserts.get(key, 0)))
    print("total %d calls, %d wrong in %d configurations, %d stopped by an assertion in %d, of %d configurations" % (
        sum(total.values()), sum(wrong.values()), len(bad_cfg), sum(asserts.values()), len(assert_cfg), len(cs)))
    json.dump(bad_cfg, open(os.path.join(out_dir, "bad_configs.json"), "w"))
    json.dump(assert_cfg, open(os.path.join(out_dir, "assert_configs.json"), "w"))


if __name__ == "__main__":
    if sys.argv[1] == "gen":
        gen(sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 8)
    else:
        check(sys.argv[2], sys.argv[3], int(sys.argv[4]) if len(sys.argv) > 4 else 2)
